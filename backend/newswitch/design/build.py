"""Build a device configuration, UI included, from an optikit design.

    uv run python -m newswitch.tools.build_design <design.dsn> -o configs/newswitch-config.<name>.yaml

The result is an ordinary ``newswitch-config.yaml`` (see ``configs/README.md``) with two
more sections, so running the microscope needs nothing but this file:

* ``devices``: the design's devices (`newswitch.design.config.design_config`);
* ``assets``: the design's 3D model, simplified into ``newswitch/assets/design/``;
* ``ui``: every blok the microscope shows, as BSX source: the 3D view and the cards its
  devices open, the fluorescence, stage and minimal views; with the catalog version they
  were written against (``catalog: newswitch@<version>``);
* ``agent_ui``: the bloks Orkestrator shows in agent mode (`newswitch.bloks.agent`), drawn
  with the spec's catalogs and Orkestrator's module (``catalog: orkestrator@<release>``):
  the camera streams, and the design's 3D view (a ``<Scene>``, ``view-3d``) with the
  cards its devices open.

Nothing is composed when newswitch starts: it reads the bloks as they are written here
(and checks them against the catalog). Rebuild after changing the design or the blok
fragments in `newswitch.bloks`; edits made by hand to the file are then overwritten.
"""

from pathlib import Path
from typing import Any

from ruamel.yaml.scalarstring import LiteralScalarString

from newswitch.config_io import BlokEntry, NewswitchConfig, adapters
from newswitch.config_io.document import _round_trip_yaml

HEADER = """\
newswitch device configuration of the optikit design {dsn}.
Generated by: uv run python -m newswitch.tools.build_design -- do not edit by hand, rebuild.
Run it with:  NEWSWITCH_CONFIG={out} just dev
"""


def compose_ui(dsn: Path, devices: NewswitchConfig) -> tuple[dict[str, str], dict[str, BlokEntry]]:
    """The design's assets and every blok its microscope shows, the 3D view first."""
    from newswitch.bloks import design, fluorescence, minimal, stage_view

    assets, bloks = design.bloks(dsn, devices)
    bloks = {"view-3d": bloks.pop("view-3d"), **bloks}
    bloks[fluorescence.NAME] = fluorescence.blok(has_filters=adapters.filters(devices) is not None)
    bloks[stage_view.NAME] = stage_view.blok(default=False)
    bloks[minimal.NAME] = minimal.blok(default=False)
    return assets, bloks


def _blok_entry(entry: BlokEntry) -> dict[str, Any]:
    """A blok as written: its source a literal block, so it reads like the BSX it is."""
    data: dict[str, Any] = {"description": entry.description}
    if entry.default:
        data["default"] = True
    data["bsx"] = LiteralScalarString(entry.bsx.strip() + "\n")
    return data


def build(dsn: Path, out: Path) -> Path:
    """Write the device configuration of the design `dsn`, its UI included, to `out`."""
    from newswitch.bloks import agent, design
    from newswitch.bloks.catalog import load_catalog
    from newswitch.design.config import design_config, design_tree

    # 1. devices: what the design's parts say they are
    devices = design_config(dsn)
    # 2. ui: the bloks built for exactly those devices, and the model they show
    assets, bloks = compose_ui(dsn, devices)
    # 3. one file: the devices as the design states them, then assets and ui
    document = {
        **design_tree(dsn),
        "assets": assets,
        "ui": {
            "catalog": load_catalog().id,
            "bloks": {name: _blok_entry(entry) for name, entry in bloks.items()},
        },
        # The same microscope as an arkitekt agent, for Orkestrator (main_arkitekt.py)
        "agent_ui": {
            "catalog": agent.AGENT_CATALOG,
            "bloks": {
                agent.NAME: _blok_entry(
                    agent.blok(has_stage=adapters.motion_stage(devices) is not None)
                ),
                **{
                    name: _blok_entry(entry)
                    for name, entry in design.agent_bloks(dsn, devices).items()
                },
            },
        },
    }

    yaml = _round_trip_yaml()
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as file:
        header = HEADER.format(dsn=dsn.name, out=out)
        file.write("".join(f"# {line}\n" for line in header.splitlines()) + "\n")
        yaml.dump(document, file)
    return out
